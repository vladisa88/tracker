import { test, expect } from '@playwright/test';

test('добавление сохраняет подписку, ошибки сохраняют ввод', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('link', {name: 'Войти через Telegram'}).click();
  await page.getByRole('link', {name: 'Владелец', exact: true}).click();
  await page.getByRole('button', {name: 'Добавить подписку', exact: true}).click();
  const name = `Интернет ${test.info().project.name} ${Date.now()}`;
  await page.getByLabel('Название').fill(name);
  await page.getByLabel('Сумма').fill('799.001');
  await page.getByLabel('Валюта').selectOption('EUR');
  await page.getByLabel('Периодичность').selectOption('90');
  await page.getByRole('button', {name: 'Сохранить подписку'}).click();
  await expect(page.getByText('Введите положительную сумму с точностью валюты')).toBeVisible();
  await expect(page.getByLabel('Название')).toHaveValue(name);
  await page.getByLabel('Сумма').fill('799.01');
  let releaseResponse;
  const responseGate = new Promise(resolve => { releaseResponse = resolve; });
  let saves = 0;
  await page.route('**/api/subscriptions', async route => {
    if (route.request().method() !== 'POST') { await route.continue(); return; }
    saves++;
    const response = await route.fetch();
    await responseGate;
    await route.fulfill({response});
  });
  // Labelled inputs and keyboard submit remain usable without pointer actions.
  await page.getByRole('button', {name: 'Сохранить подписку'}).focus();
  await page.keyboard.press('Enter');
  await expect(page.getByRole('button', {name:'Сохраняем…'})).toBeDisabled();
  await expect(page.getByRole('status').filter({hasText:'Подписка добавлена'})).toHaveCount(0);
  releaseResponse();
  await expect(page.getByRole('status').filter({hasText:'Подписка добавлена'})).toBeVisible();
  expect(saves).toBe(1);
  const item = page.getByRole('listitem').filter({hasText:name});
  await expect(item).toContainText('799.01 EUR');
  await expect(item).toContainText('90 дней');
  await page.reload();
  await expect(item).toBeVisible();
  await expect(item).toContainText('799.01 EUR');
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', await page.evaluate(() => document.body.clientWidth));
});

test('редактирование, архив и восстановление сохраняются после перезагрузки', async ({page}) => {
  await page.goto('/');
  await page.getByRole('link', {name:'Войти через Telegram'}).click();
  await page.getByRole('link', {name:'Владелец', exact:true}).click();
  await page.getByRole('button', {name:'Добавить подписку', exact:true}).click();
  const original = `Архив ${test.info().project.name} ${Date.now()}`;
  const renamed = `${original} изменён`;
  await page.getByLabel('Название').fill(original);
  await page.getByLabel('Сумма').fill('500');
  const date = await page.getByLabel('Следующая дата платежа').inputValue();
  await page.getByRole('button', {name:'Сохранить подписку'}).click();
  let item = page.getByRole('listitem').filter({hasText:original});
  await item.getByRole('button', {name:'Редактировать', exact:true}).focus();
  await page.keyboard.press('Enter');
  await page.getByLabel('Название').fill(renamed);
  await page.getByLabel('Сумма').fill('0');
  await page.getByRole('button', {name:'Сохранить изменения'}).click();
  await expect(page.getByText('Введите положительную сумму с точностью валюты')).toBeVisible();
  await expect(page.getByLabel('Название')).toHaveValue(renamed);
  await page.getByLabel('Сумма').fill('700.99');
  await page.getByLabel('Валюта').selectOption('USD');
  await page.getByLabel('Периодичность').selectOption('180');
  await expect(page.getByLabel('Следующая дата платежа')).toHaveValue(date);
  await page.getByRole('button', {name:'Сохранить изменения'}).click();
  await expect(page.getByRole('status').filter({hasText:'Изменения сохранены'})).toBeVisible();
  item = page.getByRole('listitem').filter({hasText:renamed});
  await page.reload();
  await expect(item).toContainText('700.99 USD');
  await expect(item).toContainText('180 дней');
  await item.getByRole('button', {name:'В архив', exact:true}).click();
  await expect(page.getByRole('status').filter({hasText:'Подписка в архиве'})).toBeVisible();
  await expect(item).toHaveCount(0);
  await page.getByRole('button', {name:'Архив', exact:true}).click();
  await expect(item).toBeVisible();
  await page.reload();
  await page.getByRole('button', {name:'Архив', exact:true}).click();
  await expect(item).toContainText('700.99 USD');
  await item.getByRole('button', {name:'Восстановить', exact:true}).click();
  await expect(page.getByLabel('Следующая дата платежа')).toHaveValue('');
  await page.getByRole('button', {name:'Восстановить подписку', exact:true}).click();
  await expect(page.getByRole('alert')).toBeVisible();
  await page.getByLabel('Следующая дата платежа').fill('2099-12-31');
  await page.getByRole('button', {name:'Восстановить подписку', exact:true}).focus();
  await page.keyboard.press('Enter');
  await expect(page.getByRole('status').filter({hasText:'Подписка восстановлена'})).toBeVisible();
  await expect(page.getByRole('button', {name:'Активные', exact:true})).toHaveAttribute('aria-pressed','true');
  await expect(item).toContainText('31.12.2099');
  await page.reload();
  await expect(item).toContainText('31.12.2099');
  await expect(item).toContainText('700.99 USD');
  const dates = await page.getByRole('list', {name:'Активные подписки', exact:true}).locator('time').evaluateAll(elements => elements.map(el => el.getAttribute('datetime')));
  expect(dates).toEqual([...dates].sort());
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', await page.evaluate(() => document.body.clientWidth));
  await page.emulateMedia({reducedMotion:'reduce'});
  expect(await item.evaluate(el => getComputedStyle(el).animationName)).toBe('none');
});
